    public void CompareBar(
        IReadOnlyList<(string Label, double ValueA, double ValueB)> items,
        string? labelA = null, string? labelB = null,
        string? unit = null, string? caption = null, string? valueMode = null)
    {
        if (items.Count == 0) return;

        bool sizeMode = string.Equals(valueMode, "size", StringComparison.Ordinal);
        string FormatVal(double v) => sizeMode
            ? DumpDetective.Core.Utilities.DumpHelpers.FormatSize((long)v)
            : $"{v:F1}{H(unit ?? "")}";

        double globalMax = items.Max(i => Math.Max(i.ValueA, i.ValueB));
        if (globalMax <= 0) return;

        const string ColorA = "#6366f1";
        const string ColorB = "#22c55e";
        string lblA = labelA ?? "A";
        string lblB = labelB ?? "B";

        if (caption is not null) _w.WriteLine($"<p class=\"caption\">{H(caption)}</p>");
        _w.WriteLine("<div class=\"chart-card cbar-card\">");

        _w.Write("<div class=\"cbar-header\">");
        _w.Write("<span></span>");
        _w.Write("<div class=\"cbar-legend\">");
        _w.Write($"<span class=\"cbar-legend-item\"><span class=\"cbar-legend-dot\" style=\"background:{ColorA}\"></span>{H(lblA)}</span>");
        _w.Write($"<span class=\"cbar-legend-item\"><span class=\"cbar-legend-dot\" style=\"background:{ColorB}\"></span>{H(lblB)}</span>");
        _w.Write("</div>");
        _w.WriteLine("</div>");

        foreach (var (label, valA, valB) in items)
        {
            double pctA = Math.Min(valA / globalMax * 100.0, 100.0);
            double pctB = Math.Min(valB / globalMax * 100.0, 100.0);
            bool   both = valA > 0 && valB > 0;

            _w.Write($"<div class=\"cbar-row{(both ? " cbar-row-match" : "")}\">");
            _w.Write($"<span class=\"cbar-lbl\" title=\"{H(label)}\">{H(label)}</span>");
            _w.Write("<div class=\"cbar-bars\">");
            _w.Write($"<div class=\"cbar-bar-row\" data-tip=\"{H(label)} — {H(lblA)}: {H(FormatVal(valA))}\"><div class=\"cbar-bar-track\"><div class=\"cbar-a\" style=\"width:{pctA:F1}%\"></div></div><span class=\"cbar-bar-val\">{H(FormatVal(valA))}</span></div>");
            _w.Write($"<div class=\"cbar-bar-row\" data-tip=\"{H(label)} — {H(lblB)}: {H(FormatVal(valB))}\"><div class=\"cbar-bar-track\"><div class=\"cbar-b\" style=\"width:{pctB:F1}%\"></div></div><span class=\"cbar-bar-val\">{H(FormatVal(valB))}</span></div>");
            _w.Write("</div>");
            _w.WriteLine("</div>");
        }
        _w.WriteLine("</div>");
    }

    public void Table(string[] headers, IReadOnlyList<string[]> rows, string? caption = null)
    {
        int tid = ++_tableSeq;
        bool large = rows.Count > 50;

        // A column literally named "Jump" holding a CLI command name (e.g. "heap-stats")
        // renders as a one-click scroll-to-evidence button instead of plain text. Other
        // sinks (Markdown/Text/JSON/...) just print the command name — this is additive,
        // not a format change, so no IRenderSink signature change was needed for it.
        int jumpCol = Array.IndexOf(headers, "Jump");

        if (caption is not null) _w.WriteLine($"<p class=\"caption\">{H(caption)}</p>");

        _w.WriteLine($"""
            <div class="table-toolbar">
              <input class="tbl-search" id="ts{tid}" placeholder="Filter rows…" oninput="filterTable({tid})" autocomplete="off">
              <span class="row-count" id="rc{tid}">{rows.Count:N0} rows</span>
              <button class="tbl-csv-btn" onclick="exportCsv({tid})" title="Export visible rows as CSV">⬇ CSV</button>
            </div>
            """);

        _w.WriteLine($"<div class=\"table-wrap{(large ? " tbl-large" : "")}\" id=\"tw{tid}\">");
        _w.WriteLine($"<table id=\"t{tid}\" class=\"data-table\">");
        _w.WriteLine("<thead><tr>");
        for (int i = 0; i < headers.Length; i++)
            _w.Write($"<th onclick=\"sortTable({tid},{i})\" title=\"Sort by {H(headers[i])}\">{H(headers[i])}<span class=\"sort-icon\">⇅</span></th>");
        _w.WriteLine("</tr></thead>");
        _w.WriteLine("<tbody>");

        for (int r = 0; r < rows.Count; r++)
        {
            var row = rows[r];
            _w.Write("<tr>");
            for (int i = 0; i < headers.Length; i++)
            {
                string cell = i < row.Length ? row[i] : string.Empty;
                string cellCls = "";
                string cellContent = H(cell);
                if (i == jumpCol && cell.Length > 0 && cell != "—")
                {
                    cellCls = " class=\"tbl-jump\"";
                    cellContent = $"<button class=\"tbl-jump-btn\" onclick=\"scrollToCommand('{cell}')\" title=\"Jump to {H(cell)} evidence\">→ {H(cell)}</button>";
                }
                else if (cell is "↑↑" or "↑↑ ↑↑") cellCls = " class=\"trend-up2\"";
                else if (cell is "↑" or "↑ ↑")  cellCls = " class=\"trend-up\"";
                else if (cell.StartsWith("↓"))    cellCls = " class=\"trend-dn\"";
                else if (cell is "Critical")      { cellCls = " class=\"sev-crit\""; cellContent = "<span class=\"sev-badge sev-badge-crit\">✗ Critical</span>"; }
                else if (cell is "Warning")       { cellCls = " class=\"sev-warn\""; cellContent = "<span class=\"sev-badge sev-badge-warn\">⚠ Warning</span>"; }
                else if (cell is "Info")          { cellCls = " class=\"sev-info\""; cellContent = "<span class=\"sev-badge sev-badge-info\">ℹ Info</span>"; }
                else if (IsMethodCell(cell))      cellCls = " class=\"method-text\"";
                else if (cell.Length > 55)        cellCls = " class=\"long-text\"";
                _w.Write($"<td{cellCls}>{cellContent}</td>");
            }
            _w.WriteLine("</tr>");
        }

        _w.WriteLine("</tbody></table></div>");
    }

