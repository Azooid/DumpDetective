    static HtmlSink()
    {
        var asm    = typeof(HtmlSink).Assembly;
        var layout = ReadResource(asm, "HtmlSink.layout.html");
        var css    = ReadResource(asm, "HtmlSink.css");
        var js     = ReadResource(asm, "HtmlSink.js");

        var full  = layout.Replace("{STYLES}", css).Replace("{SCRIPTS}", js);
        const string split = "{DOC_SPLIT}";
        int idx   = full.IndexOf(split, StringComparison.Ordinal);
        s_docHeader = full[..idx];
        s_footer    = full[(idx + split.Length)..];
    }

    static string ReadResource(Assembly asm, string name)
    {
        using var stream = asm.GetManifestResourceStream(name)
            ?? throw new InvalidOperationException($"Missing embedded resource: {name}");
        using var reader = new System.IO.StreamReader(stream);
        return reader.ReadToEnd();
    }
